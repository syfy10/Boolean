// Builds site/app-live-demo.html: a self-contained, interactive copy of the real
// app UI (src/ui.html) with the demo runtime + sanitized fixtures injected in
// <head>, so it runs fully client-side with scripted replies and no backend.
//
//   node site/demo/build-demo.mjs
//
// Regenerate fixtures first (from a live capture) if the UI's API shapes change:
//   node site/demo/gen-fixtures.mjs <captureDir>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const uiPath = path.join(root, "src", "ui.html");
const outPath = path.join(root, "site", "app-live-demo.html");

let html = fs.readFileSync(uiPath, "utf8");
const fixtures = fs.readFileSync(path.join(here, "fixtures.json"), "utf8");
const runtime = fs.readFileSync(path.join(here, "demo-runtime.js"), "utf8");

// Drop icon/manifest links that would 404 when served from /site.
html = html.replace(/\s*<link rel="(?:icon|apple-touch-icon|manifest)"[^>]*>/g, "");

// Escape "<" so neither the JSON nor the runtime can prematurely close the script.
const safeJson = fixtures.replace(/</g, "\\u003c");
const safeRuntime = runtime.replace(/<\/script>/gi, "<\\/script>");

const inject =
  '\n<!-- Boollm interactive demo runtime (generated by site/demo/build-demo.mjs — do not edit here) -->\n' +
  '<script>window.__DEMO_FIXTURES__ = ' + safeJson + ';</script>\n' +
  '<script>\n' + safeRuntime + '\n</script>\n';

// Insert immediately after <head> so the fetch shim installs before app scripts.
if (!/<head[^>]*>/i.test(html)) throw new Error("no <head> found in ui.html");
html = html.replace(/(<head[^>]*>)/i, "$1" + inject);

fs.writeFileSync(outPath, html);
console.log("wrote", outPath, "(" + Math.round(fs.statSync(outPath).size / 1024) + " KB)");
